# 1. Parent (Base) Class
class MachineTool:
    def __init__(self, machine_id, max_rpm):
        self.machine_id = machine_id
        self.max_rpm = max_rpm
        self.is_running = False

    def start_spindle(self):
        self.is_running = True
        print(f"[{self.machine_id}] Base spindle motor energized (Max: {self.max_rpm} RPM).")

    def execute_operation(self):
        print(f"[{self.machine_id}] Running generic machine cycle.")


# 2. Child (Derived) Class 1: CNC Lathe
class CNCLathe(MachineTool):
    def __init__(self, machine_id, max_rpm, turret_stations):
        # Initialize base MachineTool attributes using super()
        super().__init__(machine_id, max_rpm)
        self.turret_stations = turret_stations

    # Overriding the parent method for turning operations
    def execute_operation(self):
        if self.is_running:
            print(f"[{self.machine_id}] Turning outer diameter using {self.turret_stations}-station turret.")
        else:
            print(f"[{self.machine_id}] ERROR: Start spindle before turning!")


# 3. Child (Derived) Class 2: VMC Milling Machine
class VMCMill(MachineTool):
    def __init__(self, machine_id, max_rpm, axes_count):
        super().__init__(machine_id, max_rpm)
        self.axes_count = axes_count

    # Overriding the parent method for milling operations
    def execute_operation(self):
        if self.is_running:
            print(f"[{self.machine_id}] Pocket milling on {self.axes_count}-axis interpolated bed.")
        else:
            print(f"[{self.machine_id}] ERROR: Start spindle before milling!")


# --- Shop-Floor Execution ---
print("=== SHOP FLOOR INHERITANCE DEMO ===")
lathe_01 = CNCLathe("LATHE-TU200", 3500, turret_stations=8)
vmc_01 = VMCMill("VMC-VF2", 8000, axes_count=4)

for machine in (lathe_01, vmc_01):
    machine.start_spindle()
    machine.execute_operation()
    print("-" * 50)

