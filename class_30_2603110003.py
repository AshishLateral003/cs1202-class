from pathlib import Path
import re

class ShopFloorQAEngine:
    """End-to-End Automated Quality Assurance & Reporting System."""

    def __init__(self, work_order, component, nominal, tolerance):
        self.work_order = work_order
        self.component = component
        self.nominal = nominal
        self.tolerance = tolerance
        self.lsl = nominal - tolerance  # Lower Specification Limit
        self.usl = nominal + tolerance  # Upper Specification Limit
        self.good_readings = []
        self.scrap_readings = []
        self.error_count = 0

    def process_log_file(self, filepath):
        """Reads raw log file, validates entries, and classifies parts."""
        raw_lines = Path(filepath).read_text().strip().splitlines()
        for line in raw_lines:
            match = re.search(r"(SN-\d+)\s*,\s*(-?\d+\.\d+)", line)
            if not match:
                self.error_count += 1
                continue

            sn, val_str = match.group(1), match.group(2)
            dia = float(val_str)
            if dia <= 0:
                self.error_count += 1
                continue

            if self.lsl <= dia <= self.usl:
                self.good_readings.append((sn, dia))
            else:
                self.scrap_readings.append((sn, dia))

    def export_certificate(self, out_filepath):
        """Generates and saves a formatted Quality Inspection Certificate."""
        all_valid = [d for _, d in self.good_readings + self.scrap_readings]
        total_inspected = len(all_valid)
        yield_pct = (len(self.good_readings) / total_inspected * 100) if total_inspected else 0.0
        mean_dia = (sum(all_valid) / total_inspected) if total_inspected else 0.0

        report_lines = [
            "==========================================================",
            "         AUTOMATED QUALITY INSPECTION CERTIFICATE         ",
            "==========================================================",
            f"Work Order ID      : {self.work_order}",
            f"Component Name     : {self.component}",
            f"Specification      : {self.nominal:.2f} +/- {self.tolerance:.2f} mm ({self.lsl:.2f} to {self.usl:.2f} mm)",
            "----------------------------------------------------------",
            f"Total Valid Parts  : {total_inspected}",
            f"Accepted (GO)      : {len(self.good_readings)}",
            f"Rejected (NO-GO)   : {len(self.scrap_readings)}",
            f"Sensor Faults Ign. : {self.error_count}",
            "----------------------------------------------------------",
            f"Process Mean Dia   : {mean_dia:.3f} mm",
            f"First-Pass Yield   : {yield_pct:.1f}%",
            f"Batch Disposition  : {'APPROVED FOR DISPATCH' if yield_pct >= 80.0 else 'HOLD FOR REVIEW'}",
            "=========================================================="
        ]
        report_content = "\n".join(report_lines)
        Path(out_filepath).write_text(report_content + "\n")
        return report_content


