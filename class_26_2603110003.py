# Class 26: Regex - Scanning Unstructured Inspection Reports
# Date: 16-Sep-26

import re

# Unstructured text dump from a shift supervisor's logbook
inspection_report = """
Shift Log 16-Sep-2026:
Inspected Part# PR-4012 on Lathe-02; recorded diameter 25.02 mm (Status: OK).
Checked Part# PR-4015 on Lathe-02; recorded diameter 24.88 mm [FAULT: E-104 Undersize].
Inspected Part# GR-8801 on Mill-01; recorded diameter 50.01 mm (Status: OK).
Checked Part# PR-4019 on Lathe-03; chatter marks detected [FAULT: E-209 SurfaceRoughness].
"""

# 1. Extract all Part Numbers matching pattern: 2 Capital Letters - 4 Digits
part_pattern = r"[A-Z]{2}-\d{4}"
all_parts = re.findall(part_pattern, inspection_report)

# 2. Extract all Fault Codes matching pattern: E- followed by 3 digits
fault_pattern = r"E-\d{3}"
all_faults = re.findall(fault_pattern, inspection_report)

# 3. Extract Part# paired with its exact measured diameter in mm using Capture Groups ()
measurement_pattern = r"Part# ([A-Z]{2}-\d{4}).*?diameter (\d+\.\d+) mm"
measured_pairs = re.findall(measurement_pattern, inspection_report)

print("=== REGEX AUTOMATED REPORT SCANNER ===")
print("Parts Inspected :", all_parts)
print("Faults Logged   :", all_faults)
print("\nExtracted Dimensional Readings:")
for part_id, dia_str in measured_pairs:
    print(f"  -> Component {part_id} : {float(dia_str):.2f} mm")

