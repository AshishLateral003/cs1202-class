import re

class InvalidSpecError(Exception):
    """Custom exception for invalid engineering measurements."""
    pass


class WorkOrderBatch:
    def __init__(self, order_id, part_name, nominal_mm, tol_mm):
        self.order_id = order_id
        self.part_name = part_name
        self.nominal_mm = nominal_mm
        self.lower_limit = nominal_mm - tol_mm
        self.upper_limit = nominal_mm + tol_mm
        self.accepted_parts = []
        self.rejected_parts = []

    def inspect_raw_entry(self, raw_log_line):
        """Parses a raw log line using Regex, validates it, and sorts into Go/No-Go bins."""
        # Pattern matches: SN-101 : 25.02 mm
        match = re.search(r"(SN-\d+)\s*:\s*(-?\d+\.\d+)", raw_log_line)
        if not match:
            raise InvalidSpecError(f"Malformed log format -> '{raw_log_line.strip()}'")

        serial_no = match.group(1)
        dia_mm = float(match.group(2))

        if dia_mm <= 0:
            raise InvalidSpecError(f"Non-physical dimension ({dia_mm} mm) on {serial_no}")

        # Go / No-Go Gauging Logic
        if self.lower_limit <= dia_mm <= self.upper_limit:
            self.accepted_parts.append((serial_no, dia_mm))
            return f"[GO]    {serial_no} ({dia_mm:.2f} mm) -> Accepted"
        else:
            self.rejected_parts.append((serial_no, dia_mm))
            return f"[NO-GO] {serial_no} ({dia_mm:.2f} mm) -> Scrap Bin"


