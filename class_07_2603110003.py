# Class 07: Data Types & Literals - Raw Material of Code
# Date: 05-Aug-26

# 1. Defining Literals of the 4 Core Data Types
part_code = "GR-SPUR-24T"          # str (String literal)
gear_teeth = 24                    # int (Integer literal)
pitch_circle_dia_mm = 48.00        # float (Floating-point literal)
module_mm = 2.0                    # float (m = D / T)
heat_treated = True                # bool (Boolean literal)

# 2. Inspecting Data Types using type()
print("=== COMPONENT MATERIAL & DATA TYPE BILL OF MATERIALS ===")
print(f"Part Code        : {part_code:<15} | Type: {type(part_code).__name__}")
print(f"Number of Teeth  : {gear_teeth:<15} | Type: {type(gear_teeth).__name__}")
print(f"Pitch Dia (mm)   : {pitch_circle_dia_mm:<15.2f} | Type: {type(pitch_circle_dia_mm).__name__}")
print(f"Gear Module (mm) : {module_mm:<15.1f} | Type: {type(module_mm).__name__}")
print(f"Heat Treated?    : {str(heat_treated):<15} | Type: {type(heat_treated).__name__}")

# 3. Implicit Type Promotion (int * float -> float)
tooth_depth_mm = 2.25 * module_mm  # 2.25 (float) * 2 (int) produces float
print("\n=== IMPLICIT TYPE CONVERSION CHECK ===")
print(f"Calculated Tooth Depth: {tooth_depth_mm} mm (Result Type: {type(tooth_depth_mm).__name__})")

