# Class 17: Functions & Arguments - Modular Fixtures for Machining Calculations
# Date: 26-Aug-26

def compute_turning_cycle(length_mm, dia_mm, vc_m_min, feed_mm_rev=0.25, passes=1):
    """
    Modular Fixture Function: Calculates RPM, Feed Rate, and Total Cycle Time.
    Includes default arguments for standard roughing feed (0.25 mm/rev) and passes (1).
    """
    # 1. Spindle RPM: N = (1000 * Vc) / (pi * D)
    rpm = (1000 * vc_m_min) / (3.1416 * dia_mm)

    # 2. Table Feed Rate (mm/min): Fm = f * N
    feed_mm_min = feed_mm_rev * rpm

    # 3. Total Cutting Time across all passes (seconds)
    time_sec = (length_mm / feed_mm_min) * 60 * passes

    # Return multiple outputs as a tuple
    return round(rpm), round(feed_mm_min, 1), round(time_sec, 1)


print("=== FUNCTION FIXTURE DEMO (POSITIONAL, DEFAULT & KEYWORD ARGS) ===")

# Call 1: Using Default Arguments (feed=0.25 mm/rev, passes=1)
rpm1, fm1, t1 = compute_turning_cycle(150, 50, 120)
print(f"Job 1 (Standard Roughing) -> Spindle: {rpm1} RPM | Feed: {fm1} mm/min | Time: {t1} s")

# Call 2: Overriding Defaults using Keyword Arguments for a 3-pass Fine Finish
rpm2, fm2, t2 = compute_turning_cycle(
    length_mm=150,
    dia_mm=50,
    vc_m_min=180,
    feed_mm_rev=0.10,
    passes=3
)
print(f"Job 2 (3-Pass Finishing)  -> Spindle: {rpm2} RPM | Feed: {fm2} mm/min | Time: {t2} s")

