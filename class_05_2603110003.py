# 1. Initial State: Raw Bar Stock vs Target Drawing Spec
current_dia = 27.5  # mm (Raw stock)
target_dia = 25.0   # mm (Declarative target)
pass_num = 0

print(f"=== STARTING TURNING RECIPE (Raw: {current_dia} mm -> Target: {target_dia} mm) ===")

# 2. Flow of Control + Stopping Condition (while current_dia > target_dia)
while current_dia > target_dia:
    pass_num += 1
    remaining_stock = round(current_dia - target_dia, 2)

    # Branching Logic (EduBlocks L3: if / else)
    if remaining_stock >= 1.0:
        depth_of_cut = 1.0
        mode = "ROUGHING PASS"
    else:
        depth_of_cut = remaining_stock
        mode = "FINISHING PASS"

    current_dia = round(current_dia - depth_of_cut, 2)
    print(f"Pass #{pass_num} [{mode:<14}] | Cut: {depth_of_cut:.2f} mm | Remaining Dia: {current_dia:.2f} mm")

print("=== STOPPING CONDITION MET: Component at Final Dimension ===")

