# 1. Initialize State Variables (Counter & Accumulator)
part_count = 0
cumulative_wear_mm = 0.00
wear_per_part_mm = 0.04
max_wear_limit_mm = 0.15  # Carbide insert replacement threshold

print("=== SHIFT STARTED: TOOL WEAR MONITORING ===")

# 2. Condition-Controlled Loop (Run until tool wear hits the limit)
while cumulative_wear_mm < max_wear_limit_mm:
    part_count += 1
    cumulative_wear_mm += wear_per_part_mm
    print(f"Part #{part_count:02d} Machined | Cumulative Flank Wear: {cumulative_wear_mm:.2f} mm")

# 3. Post-Loop Alert (Triggered when loop condition becomes False)
print("\n[ALERT] Tool Wear Limit Exceeded!")
print(f"Total Parts Produced Before Tool Change: {part_count} units")

