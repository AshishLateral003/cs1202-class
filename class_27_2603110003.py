log_filename = "shift_production_log.csv"

# 1. Write initial CSV header and batch records ('w' mode)
with open(log_filename, mode="w") as file:
    file.write("Part_ID,Diameter_mm,Cycle_Sec\n")
    file.write("SH-001,25.01,14.2\n")
    file.write("SH-002,24.97,13.8\n")
    file.write("SH-003,25.08,14.5\n")

# 2. Append a late-shift part entry ('a' mode)
with open(log_filename, mode="a") as file:
    file.write("SH-004,25.00,14.0\n")

# 3. Read the production log back and compute summary statistics ('r' mode)
print("=== READING PRODUCTION LOG FROM DISK ===")
total_cycle_time = 0.0
accepted_count = 0
total_parts = 0

with open(log_filename, mode="r") as file:
    header = file.readline().strip()  # Skip header line
    for line in file:
        part_id, dia_str, cycle_str = line.strip().split(",")
        dia = float(dia_str)
        cycle = float(cycle_str)

        total_parts += 1
        total_cycle_time += cycle

        # Go / No-Go Check (24.95 to 25.05 mm)
        is_go = 24.95 <= dia <= 25.05
        if is_go:
            accepted_count += 1

        status_tag = "GO" if is_go else "NO-GO"
        print(f"Loaded {part_id} | Dia: {dia:.2f} mm | Cycle: {cycle:.1f}s -> [{status_tag}]")

print("\n=== SHIFT LOG SUMMARY ===")
print(f"Total Parts Logged : {total_parts}")
print(f"First-Pass Yield   : {accepted_count}/{total_parts} ({(accepted_count/total_parts)*100:.1f}%)")
print(f"Mean Cycle Time    : {total_cycle_time/total_parts:.2f} seconds")

