"""Class 08 | 05-Aug-26Topic: Operators & I/O · Feeds and Speeds1. Core Theory & Production AnalogyArithmetic Operators (The Machinist's Handbook Formulas): Python provides seven arithmetic operators to compute shop-floor machining parameters:+, -, *: Addition, subtraction, multiplication./ (True Division): Always returns a float (e.g., calculating exact cutting time $T = L / (f \times N)$).// (Floor Division): Returns the whole integer quotient, discarding the remainder (e.g., how many full $150\text{ mm}$ blanks can be cut from a $1000\text{ mm}$ bar?).% (Modulo / Remainder): Returns the leftover scrap length after floor division (e.g., $1000 \pmod{150} = 100\text{ mm}$ bar remnant).** (Exponentiation): Raising to a power (e.g., Taylor's Tool Life Equation $V \cdot T^n = C \implies T = (C/V)^{(1/n)}$, or calculating cross-sectional area $\frac{\pi}{4} D^2$).Operator Precedence (PEMDAS): Just like engineering calculators, Python evaluates parentheses () first, then exponents **, then * / // %, and finally + -."""

# Class 08: Operators & I/O - Feeds, Speeds, MRR & Bar Stock Allocation
# Date: 05-Aug-26

# 1. Simulated Operator I/O Parameters for a Turning Operation
raw_bar_length_mm = 1000     # 1-meter standard bar stock
part_length_mm = 135         # Length per part including parting-off kerf

work_dia_mm = 40.0           # D (mm)
depth_of_cut_mm = 2.0        # d (mm)
feed_mm_rev = 0.25           # f (mm/rev)
spindle_rpm = 800            # N (rev/min)

# 2. Bar Stock Utilization using Floor Division (//) and Modulo (%)
parts_per_bar = raw_bar_length_mm // part_length_mm
scrap_remnant_mm = raw_bar_length_mm % part_length_mm

# 3. Feeds, Speeds & Material Removal Rate (MRR) using *, /, and **
# Cutting Speed Vc = (pi * D * N) / 1000 (m/min)
vc_m_min = (3.1416 * work_dia_mm * spindle_rpm) / 1000

# Linear Feed Rate Fm = f * N (mm/min)
feed_rate_mm_min = feed_mm_rev * spindle_rpm

# Cross-sectional Area A = (pi / 4) * D^2 using exponentiation (**)
cross_area_mm2 = (3.1416 / 4) * (work_dia_mm ** 2)

# Material Removal Rate (MRR) = 1000 * Vc * d * f (mm^3/min)
mrr_mm3_min = 1000 * vc_m_min * depth_of_cut_mm * feed_mm_rev

print("=== 1. BAR STOCK ALLOCATION (// and %) ===")
print(f"Raw Bar Length : {raw_bar_length_mm} mm | Part Length: {part_length_mm} mm")
print(f"Full Parts Cut : {parts_per_bar} units (using //)")
print(f"Bar Remnant    : {scrap_remnant_mm} mm scrap left in chuck (using %)")

print("\n=== 2. FEEDS, SPEEDS & MRR REPORT (*, /, **) ===")
print(f"Bar Cross Area : {cross_area_mm2:.2f} mm^2")
print(f"Cutting Speed  : {vc_m_min:.2f} m/min")
print(f"Linear Feed    : {feed_rate_mm_min:.1f} mm/min")
print(f"Machining MRR  : {mrr_mm3_min / 1000:.2f} cm^3/min")

