# Class 19: OOP I - Modeling a Lathe as a Class (Blueprint vs. Instances)
# Date: 02-Sep-26

class Lathe:
    """Blueprint modeling a shop-floor Lathe machine."""

    def __init__(self, machine_id, swing_mm, current_rpm=0):
        # Instance Attributes (State of each individual lathe)
        self.machine_id = machine_id
        self.swing_mm = swing_mm
        self.current_rpm = current_rpm
        self.spindle_on = False
        self.parts_machined = 0

    # Instance Methods (Behaviors/Actions the lathe can perform)
    def engage_spindle(self, target_rpm):
        self.current_rpm = target_rpm
        self.spindle_on = True
        print(f"[{self.machine_id}] Spindle ENGAGED at {self.current_rpm} RPM.")

    def machine_part(self, part_name):
        if not self.spindle_on:
            print(f"[{self.machine_id}] INTERLOCK BLOCK: Cannot turn '{part_name}' while spindle is OFF!")
            return
        self.parts_machined += 1
        print(f"[{self.machine_id}] Machined '{part_name}' | Shift Tally: {self.parts_machined}")

    def stop_spindle(self):
        self.current_rpm = 0
        self.spindle_on = False
        print(f"[{self.machine_id}] Spindle STOPPED. Safe to open chuck guard.")


# --- Instantiating Two Independent Lathe Objects from the Class Blueprint ---
print("=== SHOP FLOOR DIGITAL TWIN: OOP INSTANCES ===")
bay1_lathe = Lathe(machine_id="LATHE-HMT-01", swing_mm=400)
bay2_lathe = Lathe(machine_id="LATHE-CNC-02", swing_mm=550)

# Operate Bay 1 Lathe
bay1_lathe.engage_spindle(1200)
bay1_lathe.machine_part("MS Stepped Shaft")
bay1_lathe.machine_part("Bronze Bush")
bay1_lathe.stop_spindle()

print("-" * 55)

# Attempt to cut on Bay 2 Lathe without starting spindle first (Independent State!)
bay2_lathe.machine_part("Alloy Gear Blank")
bay2_lathe.engage_spindle(2400)
bay2_lathe.machine_part("Alloy Gear Blank")

