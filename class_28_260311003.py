# Class 28: Files II - Directory Management & Multi-File Batch Jobs
# Date: 23-Sep-26

from pathlib import Path

# 1. Create a simulated directory for incoming shop-floor machine logs
log_dir = Path("shop_floor_logs")
log_dir.mkdir(exist_ok=True)

# 2. Generate 3 separate machine log files to simulate end-of-shift uploads
sample_machine_files = {
    "lathe_01.csv": ["25.01", "24.99", "25.04"],
    "lathe_02.csv": ["25.11", "24.96", "25.00"],
    "lathe_03.csv": ["24.95", "24.89", "25.02"]
}

for fname, readings in sample_machine_files.items():
    file_path = log_dir / fname
    file_path.write_text("\n".join(readings) + "\n")

# 3. BATCH JOB: Scan directory for all .csv files and aggregate plant yield
print("=== EXECUTING NIGHTLY PLANT BATCH JOB ===")
plant_total_parts = 0
plant_good_parts = 0

# .glob("*.csv") finds all CSV files inside shop_floor_logs/
for csv_path in sorted(log_dir.glob("*.csv")):
    lines = csv_path.read_text().strip().splitlines()
    measurements = [float(val) for val in lines]

    # Filter GO parts within 25.00 +/- 0.05 mm
    good_in_file = [d for d in measurements if 24.95 <= d <= 25.05]

    plant_total_parts += len(measurements)
    plant_good_parts += len(good_in_file)

    print(f"Processed {csv_path.name:<14} | Parts: {len(measurements)} | Accepted: {len(good_in_file)}")

# 4. Write Master Consolidated Report
master_report = Path("master_plant_summary.txt")
yield_pct = (plant_good_parts / plant_total_parts) * 100
summary_text = (
    f"PLANT BATCH REPORT (23-Sep-26)\n"
    f"Total Parts Inspected : {plant_total_parts}\n"
    f"Total Parts Accepted  : {plant_good_parts}\n"
    f"Overall Plant Yield   : {yield_pct:.2f}%\n"
)
master_report.write_text(summary_text)

print("\n=== MASTER SUMMARY SAVED TO DISK ===")
print(master_report.read_text().strip())

