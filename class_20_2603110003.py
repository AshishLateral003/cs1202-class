"""Class 20 | 02-Sep-26
Topic: OOP II · Encapsulation, Abstraction
1. Core Theory & Production Analogy
Encapsulation (Sheet-Metal Safety Enclosure & Locked PLC Cabinet): On a CNC machine, you don't leave high-voltage servo drives or gearbox governors exposed where anyone can bump them and set the spindle to 99,000 RPM. Encapsulation hides internal data inside the class using a double underscore prefix (self.__spindle_rpm), making the attribute Private. External code can only read or change it through controlled Getter and Setter methods that enforce safety limits.

Abstraction (The Operator Push-Button Panel): When an operator presses the green EXECUTE FACING CYCLE button, they don't need to manually calculate servo voltage PWM, open the solenoid coolant relay, and interpolate ball-screw steps. Abstraction hides complex internal helper sub-routines behind a clean, simple public interface.
"""

# Class 20: OOP II - Encapsulation (Private Attributes) & Abstraction
# Date: 02-Sep-26

class IndustrialCNCLathe:
    def __init__(self, model_name, max_safe_rpm=3000):
        self.model_name = model_name
        self.__max_safe_rpm = max_safe_rpm  # Private attribute (Locked rating)
        self.__spindle_rpm = 0               # Private attribute (Protected state)

    # --- ENCAPSULATION: Controlled Getter & Setter with Safety Interlock ---
    def get_rpm(self):
        """Getter: Safely reads the private spindle speed."""
        return self.__spindle_rpm

    def set_rpm(self, requested_rpm):
        """Setter: Validates requested speed against physical machine limits."""
        if requested_rpm < 0:
            print(f"[GOVERNOR REJECTED] RPM ({requested_rpm}) cannot be negative!")
        elif requested_rpm > self.__max_safe_rpm:
            print(f"[GOVERNOR CLAMPED] {requested_rpm} RPM exceeds limit! Clamping to {self.__max_safe_rpm} RPM.")
            self.__spindle_rpm = self.__max_safe_rpm
        else:
            self.__spindle_rpm = requested_rpm
            print(f"[GOVERNOR OK] Spindle speed set to {self.__spindle_rpm} RPM.")

    # --- ABSTRACTION: High-Level Public Button Hiding Internal PLC Steps ---
    def run_automated_facing_cycle(self, workpiece_dia_mm):
        """Public interface: Operator calls one simple method to run the whole cycle."""
        print(f"\n=== STARTING AUTOMATED FACING CYCLE ({self.model_name}) ===")
        self.__lock_hydraulic_chuck()
        self.__activate_flood_coolant()
        print(f"  -> Feeding tool across {workpiece_dia_mm} mm face at {self.__spindle_rpm} RPM...")
        self.__retract_turret_home()
        print("=== FACING CYCLE COMPLETE ===")

    # Private helper methods hidden from the operator (Abstraction)
    def __lock_hydraulic_chuck(self):
        print("  [Internal PLC] Hydraulic chuck pressure locked at 25 bar.")

    def __activate_flood_coolant(self):
        print("  [Internal PLC] High-pressure coolant pump energized.")

    def __retract_turret_home(self):
        print("  [Internal PLC] Coolant off. Turret rapid-retracted to X0 Z100.")


# --- Testing Encapsulation & Abstraction ---
cnc = IndustrialCNCLathe("MAZAK-QT-250", max_safe_rpm=3500)

# 1. Test Encapsulation Governor (Preventing dangerous overspeed)
cnc.set_rpm(-400)   # Blocked by setter
cnc.set_rpm(6000)   # Clamped to 3500 RPM max limit
cnc.set_rpm(1800)   # Valid speed accepted

# 2. Test Abstraction (One simple call triggers the complex internal sequence)
cnc.run_automated_facing_cycle(workpiece_dia_mm=60.0)

