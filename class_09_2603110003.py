# Class 09: Conditionals & Loops - Go / No-Go Gauging & E-Stop Logic
# Date: 06-Aug-26
# Drawing Spec: 25.00 +/- 0.05 mm (LSL = 24.95 mm, USL = 25.05 mm)

LSL = 24.95  # Lower Specification Limit
USL = 25.05  # Upper Specification Limit

# Batch of measured shaft diameters (0.00 = sensor drop; two undersize at end = tool chipped)
batch_measurements = [25.01, 25.08, 0.00, 24.97, 24.89, 24.85, 25.00]

go_count = 0
rework_count = 0
scrap_count = 0
consecutive_scrap = 0

print("=== AUTOMATED GO / NO-GO GAUGING STATION ===")

for part_no, dia in enumerate(batch_measurements, start=1):
    # 1. 'continue' Example: Skip faulty zero probe reading
    if dia <= 0.0:
        print(f"Part #{part_no:02d} | [PROBE MISS] Reading 0.00 mm -> Skipping cycle (continue)")
        continue

    # 2. 3-Way Go / No-Go Classification (if / elif / else)
    if LSL <= dia <= USL:
        status = "GO (Accepted)"
        go_count += 1
        consecutive_scrap = 0  # Reset consecutive fault counter
    elif dia > USL:
        status = "NO-GO: OVERSIZE (Send to Rework Skim)"
        rework_count += 1
        consecutive_scrap = 0
    else:
        status = "NO-GO: UNDERSIZE (Scrap Bin)"
        scrap_count += 1
        consecutive_scrap += 1

    print(f"Part #{part_no:02d} | Measured: {dia:.2f} mm -> {status}")

    # 3. 'break' Example: Stop line if 2 consecutive parts are undersize (Tool Failure)
    if consecutive_scrap >= 2:
        print("\n[E-STOP TRIGGERED] 2 consecutive undersize parts detected! Check carbide insert.")
        break

print("\n=== SHIFT INSPECTION TALLY ===")
print(f"Accepted (GO) : {go_count} | Rework (Oversize) : {rework_count} | Scrap (Undersize) : {scrap_count}")

