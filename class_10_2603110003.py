# 1. Three import styles from Python's Standard Library Tool Crib
import math
from math import atan, degrees
import statistics as stats

# --- Application 1: Taper Turning Half-Angle Calculation (using math) ---
# Formula: tan(alpha) = (D - d) / (2 * L)
major_dia_D = 50.0   # mm
minor_dia_d = 35.0   # mm
taper_len_L = 100.0  # mm

tan_alpha = (major_dia_D - minor_dia_d) / (2 * taper_len_L)
alpha_rad = atan(tan_alpha)          # Returns angle in radians
alpha_deg = degrees(alpha_rad)       # Converts radians to degrees for compound rest swivel

# Exact surface area of cylindrical stock using math.pi
stock_surface_area = math.pi * major_dia_D * taper_len_L

print("=== 1. TAPER TURNING COMPOUND REST SETUP (math module) ===")
print(f"Major Dia (D): {major_dia_D} mm | Minor Dia (d): {minor_dia_d} mm | Length (L): {taper_len_L} mm")
print(f"Tan(alpha) Ratio          : {tan_alpha:.4f}")
print(f"Compound Slide Swivel     : {alpha_deg:.2f} degrees")
print(f"Cylindrical Area (math.pi): {stock_surface_area:.2f} mm^2")

# --- Application 2: SPC Quality Control Audit (using statistics as stats) ---
sample_batch_mm = [25.01, 24.99, 25.00, 25.02, 24.98, 25.00]
batch_mean = stats.mean(sample_batch_mm)
batch_std_dev = stats.stdev(sample_batch_mm)

print("\n=== 2. STATISTICAL PROCESS CONTROL AUDIT (statistics module) ===")
print(f"Sample Readings (mm)      : {sample_batch_mm}")
print(f"Process Mean (X-bar)      : {batch_mean:.4f} mm")
print(f"Standard Deviation (Sigma): {batch_std_dev:.4f} mm")

