# Class 02: Automated Batch Counter & Go/No-Go Inspection
# Date: 22-Jul-26
# Target Spec: 25.00 +/- 0.05 mm (Acceptable range: 24.95 to 25.05 mm)

good_parts = 0
scrap_parts = 0

# Simulated measurements from 5 machined shafts (in mm)
measured_batch = [25.00, 24.98, 25.12, 24.95, 24.89]

print("=== STARTING BATCH INSPECTION (5 UNITS) ===")

# C-Block Equivalent: Repeat for each part in the batch
for index, diameter in enumerate(measured_batch, start=1):
    # Diamond Boolean Equivalent: Go / No-Go Check
    if diameter >= 24.95 and diameter <= 25.05:
        good_parts += 1
        status = "GO (Accepted)"
    else:
        scrap_parts += 1
        status = "NO-GO (Scrap)"

    print(f"Part #{index} | Measured: {diameter:.2f} mm -> {status}")

# Broadcast Equivalent: Batch Complete Summary
print("\n=== BATCH COMPLETE REPORT ===")
print("Total Accepted (Good) :", good_parts)
print("Total Rejected (Scrap):", scrap_parts)

