# --- 1. LAMBDA FUNCTIONS: Sorting Work Orders by Scrap Rate ---
# List of tuples: (Work_Order_ID, Batch_Size, Scrap_Count)
shift_batches = [
    ("WO-301", 200, 4),   # 2.0% scrap
    ("WO-302", 100, 9),   # 9.0% scrap
    ("WO-303", 150, 3),   # 2.0% scrap
    ("WO-304", 80,  4)    # 5.0% scrap
]

# Sort batches from highest scrap percentage to lowest using an inline lambda key
sorted_by_scrap = sorted(
    shift_batches,
    key=lambda batch: (batch[2] / batch[1]) * 100,
    reverse=True
)

print("=== 1. LAMBDA SORT: WORK ORDERS RANKED BY SCRAP % ===")
for wo_id, total, scrap in sorted_by_scrap:
    pct = (scrap / total) * 100
    print(f"Batch {wo_id} | Scrap: {scrap:>2}/{total:<3} ({pct:.1f}%)")


# --- 2. RECURSION: Multi-Stage Wire Drawing Die Schedule ---
def wire_drawing_schedule(current_dia_mm, target_dia_mm, reduction_factor=0.90, pass_no=0):
    """
    Recursively calculates wire diameter after successive drawing dies (10% dia reduction/pass)
    until the wire reaches or drops below target_dia_mm (Base Case).
    """
    print(f"  Die Stage #{pass_no} -> Wire Diameter: {current_dia_mm:.2f} mm")

    # Base Case: Target diameter achieved
    if current_dia_mm <= target_dia_mm:
        return pass_no

    # Recursive Step: Pass wire through the next reduction die
    next_dia = current_dia_mm * reduction_factor
    return wire_drawing_schedule(next_dia, target_dia_mm, reduction_factor, pass_no + 1)

print("\n=== 2. RECURSIVE WIRE DRAWING DIE SCHEDULE (10.0 mm -> 6.5 mm) ===")
total_dies = wire_drawing_schedule(current_dia_mm=10.0, target_dia_mm=6.5)
print(f"Total Drawing Dies Required: {total_dies} stages")

