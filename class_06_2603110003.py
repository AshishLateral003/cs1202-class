# 1. Level 6 Concept: Reusable Function (Sub-Program)
def calculate_surface_speed(diameter_mm, spindle_rpm):
    """Calculates cutting speed Vc (m/min) = (pi * D * N) / 1000"""
    vc = (3.1416 * diameter_mm * spindle_rpm) / 1000
    return round(vc, 2)

# 2. Level 5 Concept: List of Workpiece Diameters in a Batch
workpiece_batch_mm = [20.0, 35.0, 50.0, 65.0]
fixed_rpm = 1200

print(f"=== SURFACE SPEED TABLE AT FIXED {fixed_rpm} RPM ===")
print(f"{'Workpiece Dia (mm)':<20} | {'Cutting Speed Vc (m/min)':<25} | {'Tool Recommendation'}")
print("-" * 72)

# 3. Iterate through the list and call the function for each item
for dia in workpiece_batch_mm:
    vc_result = calculate_surface_speed(dia, fixed_rpm)

    # Recommend tool material based on cutting speed
    tool_type = "HSS Tool OK" if vc_result < 100 else "Use Carbide Insert"
    print(f"{dia:<20.1f} | {vc_result:<25.2f} | {tool_type}")

