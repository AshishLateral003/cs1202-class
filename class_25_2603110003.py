"""Class 25 | 16-Sep-26
Topic: String Methods & Formatting
1. Core Theory & Production Analogy
Data Cleaning (Deburring Raw Castings): Raw text coming from barcode scanners, serial ports, or operator logs often has extra spaces, newline characters (\n), or inconsistent casing (like "  lathe-01\n"). String methods act like a deburring station:

.strip(): Removes leading/trailing whitespace and newlines.

.upper() / .lower(): Standardizes text case for reliable comparisons.

.split(delimiter): Chops a comma- or dash-separated string into a clean Python list of individual tokens.

.replace(old, new): Swaps out obsolete codes or faulty characters.

Formatted String Literals (f-strings = Precision Digital Readout): When generating an inspection table, raw floating-point numbers (25.000000003) look messy. Python f-strings allow inline alignment (<, >, ^) and decimal precision (:.3f) so reports line up like a calibrated CMM printout.
"""

# Class 25: String Methods & Formatting - Deburring Raw Serial Logs
# Date: 16-Sep-26

# 1. Raw, messy barcode/serial strings from shop-floor scanners
raw_scanner_logs = [
    "  batch-101 | ms_shaft | 25.0124 | pass \n",
    "BATCH-102 | gear_blank | 49.9410 | fail   ",
    "   batch-103 | gudgeon_pin | 15.0002 | pass\n"
]

print("=== FORMATTED CMM QUALITY REPORT ===")
# Table Header using f-string alignment (< left, > right, ^ center)
print(f"{'BATCH ID':<12} | {'COMPONENT':<14} | {'MEASURED (mm)':>14} | {'STATUS':^8}")
print("-" * 57)

for raw_line in raw_scanner_logs:
    # Step 1: Deburr whitespace/newlines and standardize to UPPERCASE
    clean_line = raw_line.strip().upper()

    # Step 2: Split by pipe '|' delimiter into distinct fields
    fields = clean_line.split("|")

    # Step 3: Clean individual fields and convert measurement to float
    batch_id = fields[0].strip()
    component = fields[1].strip().replace("_", " ")
    dimension = float(fields[2].strip())
    status = fields[3].strip()

    # Step 4: Print aligned row with 3-decimal micron precision (:.3f)
    print(f"{batch_id:<12} | {component:<14} | {dimension:>14.3f} | {status:^8}")

