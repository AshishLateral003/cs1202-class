"""Class 15 | 20-Aug-26
Topic: Tuples & Sets
1. Core Theory & Production Analogy
Tuples (( ) = Locked Calibration Gauge Blocks): Unlike lists, Tuples are Immutable. Once created, their values cannot be altered, sorted, or deleted. In manufacturing, you store machine home coordinates (X, Y, Z) or drawing tolerance limits (nominal, lsl, usl) in a tuple so a buggy function can never accidentally overwrite the reference blueprint. Tuples also support Unpacking (x, y, z = home_pos).

Sets ({ } = De-Duplicated Supplier Registry & Venn Auditing): A Set is an unordered collection of unique elements—it automatically strips out duplicates! Sets support fast mathematical Venn-diagram operations:

Intersection (&): Machines certified for both Turning AND Milling.

Difference (-): Scheduled work orders that have not yet passed quality inspection.

Union (|): Combined list of all unique tools used across Shift A and Shift B.
"""

# Class 15: Tuples & Sets - Locked Blueprint Specs & Unique Batch Auditing
# Date: 20-Aug-26

# 1. TUPLES: Immutable CNC Machine Home Coordinates & Spec Unpacking
cnc_home_xyz = (0.0, 0.0, 150.0)      # Locked tuple (X, Y, Z in mm)
shaft_spec = ("MS-SHAFT-25", 24.95, 25.05)

# Tuple Unpacking into individual variables
part_id, lsl, usl = shaft_spec

print("=== 1. TUPLE UNPACKING (LOCKED BLUEPRINT SPECS) ===")
print(f"CNC Safe Home (X, Y, Z) : {cnc_home_xyz} mm")
print(f"Unpacked Part Spec      : ID={part_id} | Range: {lsl} to {usl} mm")

# 2. SETS: Removing Duplicate Barcode Scans & Venn Diagram Auditing
raw_rfid_scans = ["WO-101", "WO-102", "WO-101", "WO-103", "WO-102", "WO-104"]
unique_work_orders = set(raw_rfid_scans)  # Automatically drops duplicate scans

# Set Operations: Tracking Completed vs. Scheduled Work Orders
scheduled_orders = {"WO-101", "WO-102", "WO-103", "WO-104", "WO-105"}
inspected_orders = {"WO-101", "WO-103", "WO-104"}

pending_inspection = scheduled_orders - inspected_orders  # Set Difference (-)
verified_complete = scheduled_orders & inspected_orders   # Set Intersection (&)

print("\n=== 2. SET AUDITING (DE-DUPLICATION & VENN OPS) ===")
print("Raw RFID Scans (with duplicates) :", raw_rfid_scans)
print("Unique Work Orders Scanned       :", sorted(unique_work_orders))
print("Verified & Inspected (&)         :", sorted(verified_complete))
print("Pending Quality Inspection (-)   :", sorted(pending_inspection))

