"""Class 21 | 03-Sep-26
Topic: OOP III · Constructor, Destructor
1. Core Theory & Production Analogy
Object Lifecycle (Machine Commissioning to Decommissioning): Every machine on a shop floor goes through a strict lifecycle: power-up and calibration at the start of a job, active production during the shift, and safe power-down/lockout at the end. In Python OOP, special "dunder" (double underscore) methods automate the start and end of an object's life:

Constructor (__init__ = Machine Commissioning & Homing): Automatically executes the exact instant a new object is created (session = CNCJobSession(...)). It initializes attributes, sets reference coordinates, and allocates resources (like opening a telemetry connection or clamping a fixture).

Destructor (__del__ = Lockout/Tagout & Safe Shutdown): Automatically executes when an object is destroyed via del object_name or when the program finishes and garbage collection reclaims memory. It performs cleanup—such as releasing hydraulic pressure, parking the spindle, or closing communication ports.

Class vs. Instance Variables (Plant-Wide Counter vs. Individual Machine State): A variable defined directly inside the class body (outside __init__) is shared across all instances, allowing the constructor and destructor to track how many machines are currently powered on across the entire shop floor.
"""

# Class 21: OOP III - Constructor (__init__) & Destructor (__del__)
# Date: 03-Sep-26

class CNCJobSession:
    """Models a CNC machining session with automatic startup and shutdown hooks."""

    # Class Attribute: Tracks total active CNC sessions across the shop floor
    active_machines = 0

    # 1. CONSTRUCTOR: Runs automatically when the object is created
    def __init__(self, machine_id, work_order, chuck_pressure_bar=25.0):
        self.machine_id = machine_id
        self.work_order = work_order
        self.chuck_pressure_bar = chuck_pressure_bar
        self.parts_completed = 0

        CNCJobSession.active_machines += 1
        print(f"[__init__ STARTUP] {self.machine_id} energized for {self.work_order}.")
        print(f"  -> Axes homed (X0, Z0) | Chuck clamped at {self.chuck_pressure_bar} bar.")
        print(f"  -> Active Shop-Floor Machines: {CNCJobSession.active_machines}\n")

    # Standard Operational Method
    def run_batch(self, count):
        self.parts_completed += count
        print(f"[OPERATION] {self.machine_id} machined {count} units (Total: {self.parts_completed}).\n")

    # 2. DESTRUCTOR: Runs automatically when object is deleted or program ends
    def __del__(self):
        CNCJobSession.active_machines -= 1
        print(f"[__del__ SHUTDOWN] {self.machine_id} ({self.work_order}) decommissioning...")
        print("  -> Spindle parked | Hydraulic chuck depressurized to 0.0 bar.")
        print(f"  -> Remaining Active Machines: {CNCJobSession.active_machines}\n")


# --- Testing Object Lifecycle on the Shop Floor ---
print("=== SHIFT LIFECYCLE LOG ===")

# Commissioning two machines (Triggers __init__ automatically)
job_bay1 = CNCJobSession("LATHE-CNC-01", "WO-501-SHAFT", chuck_pressure_bar=30.0)
job_bay2 = CNCJobSession("VMC-MILL-02", "WO-502-FLANGE", chuck_pressure_bar=22.0)

# Running production cycles
job_bay1.run_batch(15)
job_bay2.run_batch(8)

# Early shutdown of Bay 1 using 'del' (Triggers __del__ immediately)
print("--- Operator shutting down Bay 1 early for tool change ---")
del job_bay1

print("--- End of Shift: Remaining machines will auto-shutdown on script exit ---")
del job_bay2

