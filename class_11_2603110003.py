# Class 11: Date-Time & Arrays - Shift Timestamps & Cycle-Time Data
# Date: 12-Aug-26

from datetime import datetime, timedelta
from array import array

# 1. Tracking Shift Start & Expected Completion using datetime & timedelta
shift_start = datetime(2026, 8, 12, 8, 0, 0)  # 12-Aug-2026 at 08:00:00 AM

# 2. Storing High-Speed Cycle Times (in seconds) using a typed float array ('d' = double float)
cycle_times_sec = array('d', [42.5, 41.8, 43.2, 42.0, 44.5, 42.0])

total_machining_sec = sum(cycle_times_sec)
avg_cycle_sec = total_machining_sec / len(cycle_times_sec)

# Calculate exact timestamp when the 6-part batch finishes
batch_end = shift_start + timedelta(seconds=total_machining_sec)

print("=== CNC CYCLE-TIME & SHIFT TELEMETRY ===")
print("Shift Start Timestamp :", shift_start.strftime("%d-%b-%Y %H:%M:%S"))
print("Batch End Timestamp   :", batch_end.strftime("%d-%b-%Y %H:%M:%S"))
print("-" * 48)
print("Array Typecode        :", cycle_times_sec.typecode, "(Homogeneous Float Array)")
print("Parts Completed       :", len(cycle_times_sec))
print(f"Total Machining Time  : {total_machining_sec:.1f} seconds")
print(f"Mean Cycle Time       : {avg_cycle_sec:.2f} seconds/part")
print(f"Hourly Production Rate: {int(3600 // avg_cycle_sec)} parts/hour")

