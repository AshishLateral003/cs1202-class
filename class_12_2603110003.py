# Class 12: Strings & Characters - Decoding Engraved Serial Numbers
# Date: 13-Aug-26

# Standard Plant Serial Format: [PLANT:5]-[DEPT:2]-[YEAR:4]-[PART_NO:4]-[GRADE:1]
serial_code = "BURLA-PE-2026-0412-A"

# 1. Indexing (Extracting single characters)
first_char = serial_code[0]      # First character from left
quality_grade = serial_code[-1]  # Last character using negative index (-1)

# 2. Slicing [start:stop] (Note: 'stop' index is excluded)
plant_location = serial_code[0:5]    # Characters 0, 1, 2, 3, 4
department = serial_code[6:8]        # Characters 6, 7
mfg_year = serial_code[9:13]         # Characters 9, 10, 11, 12
part_number = serial_code[14:18]     # Characters 14, 15, 16, 17

# 3. Step Slicing [::step] (Reversing string for barcode mirror check)
reversed_serial = serial_code[::-1]

print("=== SERIAL NUMBER LASER DECODER ===")
print("Full Engraved Code :", serial_code)
print("Code Length        :", len(serial_code), "characters")
print("-" * 42)
print("Plant Location     :", plant_location)
print("Department Code    :", department)
print("Manufacturing Year :", mfg_year)
print("Component Batch ID :", part_number)
print("Quality Grade      :", quality_grade)
print("Mirror Scan [::-1] :", reversed_serial)

# 4. Demonstrating String Concatenation (Minting an updated revision code)
upgraded_serial = serial_code[:-1] + "S"  # Replace last char with 'S' (Special Precision)
print("Upgraded Revision  :", upgraded_serial)

