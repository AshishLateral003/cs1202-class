# 1. Define Custom Shop-Floor Exception Classes
class SpindleOverheatError(Exception):
    """Raised when spindle bearing temperature exceeds safe operating limits."""
    pass

class NegativeDimensionError(Exception):
    """Raised when a sensor or operator inputs a negative physical dimension."""
    pass


# 2. Inspection & Monitoring Function using 'raise'
def monitor_cutting_pass(part_dia_mm, bearing_temp_c):
    if part_dia_mm <= 0:
        raise NegativeDimensionError(f"Invalid diameter ({part_dia_mm} mm). Must be > 0.")

    if bearing_temp_c > 85.0:
        raise SpindleOverheatError(f"Bearing at {bearing_temp_c}°C! Exceeds 85.0°C thermal limit.")

    print(f"[OK] Pass verified -> Dia: {part_dia_mm:.2f} mm | Spindle Temp: {bearing_temp_c:.1f}°C")


# --- Running a Multi-Pass Batch with Fault Isolation ---
sensor_readings = [
    (25.02, 62.5),  # Pass 1: Normal
    (25.00, 91.2),  # Pass 2: Overheating fault
    (-24.98, 65.0), # Pass 3: Sensor glitch (negative diameter)
    (24.99, 68.0)   # Pass 4: Normal
]

print("=== STARTING ROBUST CNC MONITORING LOOP ===")
for pass_num, (dia, temp) in enumerate(sensor_readings, start=1):
    try:
        print(f"\nChecking Pass #{pass_num}:")
        monitor_cutting_pass(dia, temp)
    except SpindleOverheatError as temp_err:
        print(f"  -> [THERMAL E-STOP] {temp_err} Activating oil chiller...")
    except NegativeDimensionError as dim_err:
        print(f"  -> [SENSOR FAULT] {dim_err} Recalibrating LVDT probe...")

