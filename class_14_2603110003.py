"""Class 14 | 19-Aug-26
Topic: Lists II · Map, Filter, Mutability
1. Core Theory & Production Analogy
The Aliasing Trap (Two Labels on the Same Bin): Because lists are mutable, writing bin_B = bin_A does not create a second bin of parts! It simply sticks a second barcode label (bin_B) onto the exact same physical bin in memory. Modifying bin_B silently alters bin_A. To create an independent physical copy, always use .copy() or slicing bin_A[:].

Transforming & Filtering Batches (map, filter, and List Comprehensions):

Mapping (Surface Coating / Unit Conversion Line): Applies the exact same transformation formula to every part in a batch (e.g., converting a list of pressures from bar to MPa).

Filtering (Automated Optical Sorting Line): Tests every part against a boolean condition and keeps only the parts that return True (e.g., keeping only Go-gauge parts).

List Comprehensions: Python's clean, one-line syntax [expression for item in list if condition] that combines mapping and filtering in a single pass.
"""

# Class 14: Lists II - Mutability, Aliasing, Map, Filter & Comprehensions
# Date: 19-Aug-26

# 1. Avoiding the Mutability Aliasing Trap with .copy()
master_batch_mm = [25.00, 25.04, 24.91, 24.98, 25.10]
backup_batch_mm = master_batch_mm.copy()  # Safe independent clone

# Modify master_batch_mm (reworking index 4 from 25.10 down to 25.01)
master_batch_mm[4] = 25.01

print("=== 1. MUTABILITY & SAFE CLONING (.copy) ===")
print("Backup Batch (Unchanged) :", backup_batch_mm)
print("Master Batch (Reworked)  :", master_batch_mm)

# 2. Using filter() and map() on the Master Batch
# Filter: Keep only GO parts between 24.95 and 25.05 mm
go_parts_mm = list(filter(lambda d: 24.95 <= d <= 25.05, master_batch_mm))

# Map: Apply 0.02 mm hard-chrome plating thickness (+0.04 mm to diameter)
plated_parts_mm = list(map(lambda d: round(d + 0.04, 2), go_parts_mm))

# 3. Equivalent One-Line List Comprehension (Pythonic Standard)
comp_plated_mm = [round(d + 0.04, 2) for d in master_batch_mm if 24.95 <= d <= 25.05]

print("\n=== 2. BATCH FILTERING & MAPPING PIPELINE ===")
print("Filtered GO Parts (mm)        :", go_parts_mm)
print("Mapped Chrome-Plated Dia (mm) :", plated_parts_mm)
print("List Comprehension Equivalent :", comp_plated_mm)

