# Class 04: EduBlocks L1-L2 - Blocks Become Text (I/O & Type Casting)
# Date: 29-Jul-26
# Formula: N = (1000 * Vc) / (pi * D)

# 1. String Variable & Basic Output (Level 1)
machine_id = "LATHE-CNC-04"
print("=== SHOP FLOOR HMI:", machine_id, "===")

# 2. Taking User Input & Type Casting (Level 2)
# In this example, assume the operator enters "50.0" for diameter
raw_dia = "50.0"  # Simulating input("Enter workpiece diameter (mm): ")
print(f"Operator entered diameter: {raw_dia} mm (Data Type: {type(raw_dia).__name__})")

# Convert text string to decimal float for engineering calculation
d_mm = float(raw_dia)
cutting_speed_vc = 150  # m/min for Mild Steel with Carbide insert

# 3. Calculate Spindle Speed (RPM)
rpm = (1000 * cutting_speed_vc) / (3.1416 * d_mm)

# 4. Cast float RPM to whole integer for the machine gearbox
final_rpm = int(rpm)

print("Calculated Exact RPM     :", round(rpm, 2))
print("Set Machine Gearbox to   :", final_rpm, "RPM")

